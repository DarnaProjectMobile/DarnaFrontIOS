import SwiftUI

enum AppTheme {
    static let primary = Color(red: 0.04, green: 0.4, blue: 1.0) // #0A66FF
    static let primaryLight = Color(red: 0.92, green: 0.95, blue: 1.0) // #EAF1FF
    static let onPrimary = Color.white
    static let background = Color.white
    static let card = Color.white
    static let textPrimary = Color.black.opacity(0.9)
    static let textSecondary = Color.black.opacity(0.6)
}

